"""Rebuild ``offerta-esempio.docx`` from ``offerta-esempio.txt``.

The docx is committed so the screenshots and the README's demo are reproducible,
and it is generated by a script so it is not an opaque binary in the repository:
anyone can read what is in it, and rebuild it after editing the text.

It carries real formatting — a heading, a bold run inside a sentence, a table —
because the point the docx makes that the plain text cannot is that write-back
edits runs in place and leaves the formatting alone. A flat one-paragraph file
would demonstrate nothing.

Every identifier comes from ``engine/tests/conftest.py``, where the checksums are
verified. A value with a broken check digit is rejected by L1, nothing is
detected, and the demo shows an empty finding list while looking correct.

    cd examples && ../engine/.venv/bin/python build_example.py
"""

from __future__ import annotations

from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt

HERE = Path(__file__).parent

# Kept next to the plain-text example on purpose: the two files say the same
# thing, so `inspect` on either one is comparable and a reader can diff them.
ROWS = [
    ("Partita IVA del cliente", "00743110157"),
    ("Codice fiscale del titolare", "RSSMRA85T10A562S"),
    ("IBAN per i pagamenti", "CH93 0076 2011 6238 5295 7"),
]


def build() -> Path:
    document = Document()

    document.add_heading("Offerta 2026-0143", level=1)
    subtitle = document.add_paragraph()
    run = subtitle.add_run("Documento riservato")
    run.italic = True
    run.font.size = Pt(10)

    document.add_heading("Fornitore", level=2)
    supplier = document.add_paragraph()
    supplier.add_run("Realise Consulting SA").bold = True
    supplier.add_run("\nBahnhofstrasse 12, 8001 Zurigo\nUID: CHE-116.281.710")

    document.add_heading("Cliente", level=2)
    client = document.add_paragraph()
    client.add_run("Ferrovie del Sud Srl").bold = True
    # Split across runs deliberately: a name a writer stores in three pieces is
    # the case core/stream.py exists for, and this is where the example shows it.
    client.add_run("\nReferente: ")
    client.add_run("Laura")
    client.add_run(" ")
    client.add_run("Esposito")
    client.add_run(", responsabile acquisti")
    client.add_run("\nEmail: l.esposito@ferroviedelsud.example")
    client.add_run("\nTelefono: +41 44 668 18 00")

    document.add_heading("Dati amministrativi", level=2)
    table = document.add_table(rows=0, cols=2)
    table.style = "Light Grid Accent 1"
    for label, value in ROWS:
        cells = table.add_row().cells
        cells[0].text = label
        cells[1].text = value

    document.add_paragraph()
    body = document.add_paragraph(
        "Il progetto sarà seguito da Mario Rossi, direttore commerciale, con il "
        "supporto di Anna Bianchi per la parte tecnica. La consegna è prevista "
        "entro marzo."
    )
    body.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    document.add_paragraph(
        "La presente offerta è regolata dal diritto svizzero e il foro "
        "competente è Zurigo."
    )

    # Metadata is part of what the example is for: it is removed and named in the
    # report, and no amount of reading the visible text reveals it.
    document.core_properties.author = "Mario Rossi"
    document.core_properties.last_modified_by = "Anna Bianchi"
    document.core_properties.company = "Realise Consulting SA"

    target = HERE / "offerta-esempio.docx"
    document.save(target)
    return target


if __name__ == "__main__":
    print(build())
